let ecouteurs = new Set()

export function souscrireLangue(ecouteur) {
  ecouteurs.add(ecouteur)
  return () => ecouteurs.delete(ecouteur)
}

function notifier() {
  ecouteurs.forEach((l) => l())
}

export function getLangue() {
  return getSettings().langue === 'en' ? 'en' : 'fr'
}

export function setLangue(langue) {
  const l = langue === 'en' ? 'en' : 'fr'
  saveSettingsLocal({ ...getSettings(), langue: l })
  notifier()
}

export function useLangue() {
  return useSyncExternalStore(souscrireLangue, getLangue)
}

export function t(cle, vars) {
  const langue = getLangue()
  const dico = TRADUCTIONS[langue] || TRADUCTIONS.fr
  let texte = dico[cle] || TRADUCTIONS.fr[cle] || cle
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      texte = texte.split(`{${k}}`).join(String(v))
    }
  }
  return texte
}
